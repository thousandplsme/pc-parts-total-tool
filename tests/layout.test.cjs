// node tests/layout.test.cjs <jsdomのインストール先>
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require(path.join(process.argv[2], 'node_modules/jsdom'));
const root = path.resolve(__dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), { runScripts: 'outside-only', url: 'https://example.test/' });
const { window } = dom;
const document = window.document;
const $ = selector => document.querySelector(selector);
window.eval(fs.readFileSync(path.join(root, 'app.js'), 'utf8'));
window.eval(fs.readFileSync(path.join(root, 'compatibility.js'), 'utf8'));
let count = 0;
const check = callback => { callback(); count++; };
const set = (selector, value) => {
  $(selector).value = value;
  $(selector).dispatchEvent(new window.Event('input', { bubbles: true }));
};
const visiblePanels = () => [...document.querySelectorAll('[role="tabpanel"]')].filter(panel => !panel.hidden).map(panel => panel.id);
check(() => assert.equal(document.querySelectorAll('[role="tab"]').length, 4));
check(() => assert.deepEqual(visiblePanels(), ['panel-parts']));
check(() => assert.equal($('#tab-parts').getAttribute('aria-selected'), 'true'));
check(() => assert.equal($('.sticky-summary').hidden, false));
set('#part-1-model', '保持する型番');
set('#part-1-price', '110000');
check(() => assert.equal($('#estimate').textContent, '55,000'));
for (const mode of ['import','parts','compatibility','help']) {
  $(`#tab-${mode}`).click();
  check(() => assert.deepEqual(visiblePanels(), [`panel-${mode}`]));
  check(() => assert.equal(document.querySelectorAll('[aria-selected="true"]').length, 1));
  check(() => assert.equal($('.sticky-summary').hidden, !['import','parts'].includes(mode)));
}
check(() => assert.equal($('.research-help').open, true));
$('#tab-compatibility').click();
check(() => assert.equal($('.compatibility-section').open, true));
set('#compat-cpu','i5-6600');
set('#compat-board','H310');
check(() => assert.equal($('#compat-result').textContent, '非対応'));
check(() => assert.ok($('#compat-reason').textContent.includes('物理的に刺さっても起動しません')));
set('#compat-cpu','');
set('#compat-board','H610');
check(() => assert.ok($('#compat-board-info').textContent.includes('CPUは第12・13・14世代')));
$('#tab-import').click();
set('#import-text','GPU：RTX 5070\nCPU：i5-12400F\nメモリ：DDR5 32GB\nSSD：NVMe 1TB\n型番だけ');
$('#import-parts').click();
check(() => assert.deepEqual(visiblePanels(), ['panel-parts']));
check(() => assert.equal(document.querySelectorAll('.part').length, 13));
check(() => assert.equal($('#part-1-model').value, '保持する型番'));
check(() => assert.equal($('#estimate').textContent, '55,000'));
check(() => assert.equal($('#parts-import-status').textContent, $('#import-status').textContent));
check(() => assert.equal(document.activeElement.id, 'part-9-model'));
check(() => assert.equal($('.sticky-summary').hidden, false));
const row = $('.part');
check(() => assert.equal(row.querySelectorAll('.fields > div').length, 4));
check(() => assert.equal(row.querySelectorAll('.fields select').length, 1));
check(() => assert.equal(row.querySelectorAll('.fields input').length, 2));
check(() => assert.equal(row.querySelectorAll('.fields .open-major').length, 1));
check(() => assert.equal(row.querySelector('.row-details').open, false));
for (const selector of ['.state','.links','.open-all','.viewing-points','.delete','.model-search']) {
  check(() => assert.ok(row.querySelector(`.row-details ${selector}`)));
}
row.querySelector('.row-details > summary').click();
check(() => assert.equal(row.querySelector('.row-details').open, true));
row.querySelector('.row-details > summary').click();
check(() => assert.equal(row.querySelector('.row-details').open, false));
set('#part-13-model', 'RTX 3060');
check(() => assert.ok($('#part-13-model').parentElement.querySelector('.category-hint button')));
set('#part-13-model', '不明な型番');
check(() => assert.equal($('#part-13-model').parentElement.querySelector('.category-hint').textContent, ''));
check(() => assert.ok(document.querySelector('.part:last-child .row-details .model-search a')));
window.open = () => null;
row.querySelector('.open-all').click();
check(() => assert.equal(row.querySelector('.site-progress').textContent, '3/3 一括オープンを実行'));
row.querySelector('.open-major').click();
check(() => assert.equal(row.querySelector('.site-progress').textContent, '1/3 オークフリーまで開いた'));
$('#tab-import').click();
set('#import-text','\n');
$('#import-parts').click();
check(() => assert.deepEqual(visiblePanels(), ['panel-import']));
$('#tab-parts').click();
$('#tab-parts').dispatchEvent(new window.KeyboardEvent('keydown', { key:'ArrowRight', bubbles:true }));
check(() => assert.equal(document.activeElement.id, 'tab-compatibility'));
check(() => assert.deepEqual(visiblePanels(), ['panel-compatibility']));
console.log(`PASS: ${count} layout assertions`);
window.close();
